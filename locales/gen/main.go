// Command gen checks Miya's message catalogs and generates their Go accessors.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"miya/internal/i18ncatalog"
)

func main() {
	dir := flag.String("dir", "locales", "directory containing en.json and its translations")
	check := flag.Bool("check", false, "validate catalogs and check that catalog_gen.go is up to date without writing")
	flag.Parse()
	if err := run(*dir, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(dir string, check bool) error {
	catalog, err := i18ncatalog.New(os.DirFS(dir), "en")
	if err != nil {
		return err
	}
	data, err := generate(catalog)
	if err != nil {
		return err
	}
	path := filepath.Join(dir, "catalog_gen.go")
	previous, err := os.ReadFile(path)
	if err == nil && bytes.Equal(data, previous) {
		return nil
	}
	if check {
		return fmt.Errorf("%s is out of date; run go generate ./locales", path)
	}
	return os.WriteFile(path, data, 0644)
}

func generate(catalog *i18ncatalog.Catalog) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by go generate ./locales. DO NOT EDIT.

package locales

// Messages say the messages in one language.
type Messages struct{ locale string }

// In returns the messages in the catalog language best matching locale.
// An empty locale selects the source language.
func In(locale string) Messages { return Messages{locale} }
`)
	used := map[string]bool{"In": true, "Messages": true, "Catalog": true, "Current": true, "Match": true,
		"SetCurrent": true, "T": true, "TextIn": true, "HasMessage": true, "CatalogFiles": true, "SetMessageLocaleFunc": true}
	for _, key := range catalog.Keys() {
		name := goName(key)
		if !token.IsIdentifier(name) || !token.IsExported(name) || used[name] {
			return nil, fmt.Errorf("message %q has invalid or conflicting Go accessor %q", key, name)
		}
		used[name] = true
		message := catalog.Format("en", key, nil)
		// Quote the preview so embedded newlines cannot alter the Go source.
		if utf8.RuneCountInString(message) > 120 {
			message = string([]rune(message)[:117]) + "…"
		}
		preview := strconv.Quote(message)
		fmt.Fprintf(&b, "\n// %s says %s\n// in the language the app shows.\n", name, preview)
		fmt.Fprintf(&b, "func %s() string { return In(messageLocale()).%s() }\n", name, name)
		fmt.Fprintf(&b, "\n// %s says %s\n// in the language of msgs.\n", name, preview)
		fmt.Fprintf(&b, "func (msgs Messages) %s() string {\n\treturn Catalog.Format(msgs.locale, %q, nil)\n}\n", name, key)
	}
	return format.Source(b.Bytes())
}

// Preserve the accessor names of the former generator: capitalize the first
// rune of each underscore-separated word, without changing internal capitals.
func goName(key string) string {
	var b strings.Builder
	for _, word := range strings.Split(key, "_") {
		if word == "" {
			continue
		}
		r, n := utf8.DecodeRuneInString(word)
		b.WriteRune(unicode.ToUpper(r))
		b.WriteString(word[n:])
	}
	return b.String()
}
